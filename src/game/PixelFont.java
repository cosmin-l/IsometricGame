package game;

import java.awt.Graphics2D;
import java.util.HashMap;
import java.util.Map;

/** A 3x5 bitmap font (uppercase only, like the old consoles). Pixel size follows the current Font size. */
final class PixelFont {
    private static final Map<Character, int[]> GLYPHS = new HashMap<>();

    static {
        def('A', ".#.", "#.#", "###", "#.#", "#.#");
        def('B', "##.", "#.#", "##.", "#.#", "##.");
        def('C', ".##", "#..", "#..", "#..", ".##");
        def('D', "##.", "#.#", "#.#", "#.#", "##.");
        def('E', "###", "#..", "##.", "#..", "###");
        def('F', "###", "#..", "##.", "#..", "#..");
        def('G', ".##", "#..", "#.#", "#.#", ".##");
        def('H', "#.#", "#.#", "###", "#.#", "#.#");
        def('I', "###", ".#.", ".#.", ".#.", "###");
        def('J', "..#", "..#", "..#", "#.#", ".#.");
        def('K', "#.#", "#.#", "##.", "#.#", "#.#");
        def('L', "#..", "#..", "#..", "#..", "###");
        def('M', "#.#", "###", "###", "#.#", "#.#");
        def('N', "##.", "#.#", "#.#", "#.#", "#.#");
        def('O', ".#.", "#.#", "#.#", "#.#", ".#.");
        def('P', "##.", "#.#", "##.", "#..", "#..");
        def('Q', ".#.", "#.#", "#.#", "##.", ".##");
        def('R', "##.", "#.#", "##.", "#.#", "#.#");
        def('S', ".##", "#..", ".#.", "..#", "##.");
        def('T', "###", ".#.", ".#.", ".#.", ".#.");
        def('U', "#.#", "#.#", "#.#", "#.#", "###");
        def('V', "#.#", "#.#", "#.#", ".#.", ".#.");
        def('W', "#.#", "#.#", "###", "###", "#.#");
        def('X', "#.#", "#.#", ".#.", "#.#", "#.#");
        def('Y', "#.#", "#.#", ".#.", ".#.", ".#.");
        def('Z', "###", "..#", ".#.", "#..", "###");
        def('0', "###", "#.#", "#.#", "#.#", "###");
        def('1', ".#.", "##.", ".#.", ".#.", "###");
        def('2', "##.", "..#", ".#.", "#..", "###");
        def('3', "##.", "..#", ".#.", "..#", "##.");
        def('4', "#.#", "#.#", "###", "..#", "..#");
        def('5', "###", "#..", "##.", "..#", "##.");
        def('6', ".##", "#..", "###", "#.#", "###");
        def('7', "###", "..#", ".#.", ".#.", ".#.");
        def('8', "###", "#.#", "###", "#.#", "###");
        def('9', "###", "#.#", "###", "..#", "##.");
        def('.', "...", "...", "...", "...", ".#.");
        def(',', "...", "...", "...", ".#.", "#..");
        def(':', "...", ".#.", "...", ".#.", "...");
        def(';', "...", ".#.", "...", ".#.", "#..");
        def('!', ".#.", ".#.", ".#.", "...", ".#.");
        def('?', "##.", "..#", ".#.", "...", ".#.");
        def('-', "...", "...", "###", "...", "...");
        def('+', "...", ".#.", "###", ".#.", "...");
        def('=', "...", "###", "...", "###", "...");
        def('_', "...", "...", "...", "...", "###");
        def('/', "..#", "..#", ".#.", "#..", "#..");
        def('\\', "#..", "#..", ".#.", "..#", "..#");
        def('%', "#.#", "..#", ".#.", "#..", "#.#");
        def('\'', ".#.", ".#.", "...", "...", "...");
        def('"', "#.#", "#.#", "...", "...", "...");
        def('(', "..#", ".#.", ".#.", ".#.", "..#");
        def(')', "#..", ".#.", ".#.", ".#.", "#..");
        def('&', ".#.", "#.#", ".#.", "#.#", ".##");
        def('#', "#.#", "###", "#.#", "###", "#.#");
        def('*', "#.#", ".#.", "#.#", "...", "...");
        def('|', ".#.", ".#.", ".#.", ".#.", ".#.");
        def('<', "..#", ".#.", "#..", ".#.", "..#");
        def('>', "#..", ".#.", "..#", ".#.", "#..");
    }

    private PixelFont() {}

    private static void def(char c, String... rows) {
        int[] bits = new int[5];
        for (int r = 0; r < 5; r++)
            for (int k = 0; k < 3; k++) if (rows[r].charAt(k) == '#') bits[r] |= 4 >> k;
        GLYPHS.put(c, bits);
    }

    /** Size of one font pixel, in the panel's (full-resolution) coordinates; always a whole retro pixel. */
    static int unit(Graphics2D g) {
        return 2 * Math.max(1, Math.round(g.getFont().getSize2D() / 11f));
    }

    static int width(Graphics2D g, String s) {
        return s.isEmpty() ? 0 : s.length() * 4 * unit(g) - unit(g);
    }

    /** Same contract as Graphics.drawString: (x, y) is the left end of the baseline. */
    static void draw(Graphics2D g, String s, int x, int y) {
        int u = unit(g), top = y - 5 * u;
        for (int i = 0; i < s.length(); i++) {
            char c = Character.toUpperCase(s.charAt(i));
            if (c != ' ') {
                int[] bits = GLYPHS.getOrDefault(c, GLYPHS.get('?'));
                for (int r = 0; r < 5; r++)
                    for (int k = 0; k < 3; k++)
                        if ((bits[r] & (4 >> k)) != 0) g.fillRect(x + k * u, top + r * u, u, u);
            }
            x += 4 * u;
        }
    }
}
